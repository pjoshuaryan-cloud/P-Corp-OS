"""Describe an edit from the phone (Cinematic Reel Autopilot phase 6b, 2026-11-18).

The phone talks to the cloud backend, but planning needs the Mac: the footage, the clip descriptions and the songs are on its drives. So a sentence typed on
the phone is left here, in the shared database, and the Mac's backend picks it up (main._edit_chat_relay_loop, Mac-only): it understands it with the same
code as the Mac's own box, writes the costed card back, and, when Josh presses Go on the phone, runs it and writes its progress back. The phone only ever
sees what the Mac wrote.

  status: new -> understanding -> understood | unclear | failed
          understood -> go -> starting -> running -> done | stopped | failed
          new / understood -> cancelled (Josh), new -> expired (the Mac didn't pick it up in time), replaced (a newer sentence)

The Mac writes a heartbeat every few seconds, so the phone can say plainly when the Mac is off. Like the on-set lists (on_set_db.py), the tables are made the
first time a sentence is sent, not at startup: startup DDL has caused an outage here before. The same SQL runs on the cloud Postgres and on local SQLite.
Nothing here spends money: the Mac's code does, only for a card Josh pressed Go on, never past its cap.
"""
from __future__ import annotations

import json
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

import aiosqlite

DB_PATH = Path(__file__).parent.parent / "data" / "edit_chat_relay.db"
MAX_TEXT = 500
MAC_ONLINE_SECONDS = 20        # the Mac beats every few seconds; no beat for this long = offline
NEW_EXPIRES_MINUTES = 15       # a sentence the Mac hasn't picked up by then is dropped (so it isn't acted on hours later)
CARD_EXPIRES_MINUTES = 30      # Go on an older card is refused: shoots, songs and costs may have changed
_COLUMNS = ("id", "text", "status", "card_json", "run_json", "message", "created_at", "updated_at")
ACTIVE = ("new", "understanding", "understood", "go", "starting", "running")


def now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%f")[:-3] + "Z"


def _ago(minutes: float) -> str:
    return (datetime.now(timezone.utc) - timedelta(minutes=minutes)).strftime("%Y-%m-%dT%H:%M:%S.%f")[:-3] + "Z"


def _table(conn: Any, name: str) -> str:
    return f"edit_chat.{name}" if conn is not None else f"edit_chat_{name}"


async def _run(conn: Any, sql: str, params: tuple = ()) -> list[tuple]:
    """One statement, the same SQL on both databases, committed."""
    if conn is not None:
        async with conn.cursor() as cur:
            await cur.execute(sql.replace("?", "%s"), params)
            rows = await cur.fetchall() if cur.description else []
        await conn.commit()
        return rows
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    async with aiosqlite.connect(DB_PATH) as db:
        async with db.execute(sql, params) as cur:
            rows = await cur.fetchall()
        await db.commit()
        return [tuple(r) for r in rows]


async def ensure_tables(conn: Any = None) -> None:
    identity = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if conn is not None else "INTEGER PRIMARY KEY AUTOINCREMENT"
    if conn is not None:
        await _run(conn, "CREATE SCHEMA IF NOT EXISTS edit_chat")
    await _run(conn, f"""CREATE TABLE IF NOT EXISTS {_table(conn, "requests")} (
        id {identity}, text TEXT NOT NULL, status TEXT NOT NULL, card_json TEXT, run_json TEXT, message TEXT, created_at TEXT NOT NULL, updated_at TEXT NOT NULL)""")
    await _run(conn, f"""CREATE TABLE IF NOT EXISTS {_table(conn, "worker")} (id INTEGER PRIMARY KEY, seen_at TEXT NOT NULL)""")


async def tables_exist(conn: Any = None) -> bool:
    try:
        await _run(conn, f"SELECT 1 FROM {_table(conn, 'worker')} LIMIT 1")
        return True
    except Exception:
        if conn is not None:
            await conn.rollback()
        return False


def _row(row: tuple | None) -> dict[str, Any] | None:
    if row is None:
        return None
    out = dict(zip(_COLUMNS, row))
    out["card"] = json.loads(out.pop("card_json")) if out.get("card_json") else None
    out["run"] = json.loads(out.pop("run_json")) if out.get("run_json") else None
    return out


async def _get(conn: Any, request_id: int) -> dict[str, Any] | None:
    rows = await _run(conn, f"SELECT {', '.join(_COLUMNS)} FROM {_table(conn, 'requests')} WHERE id = ?", (request_id,))
    return _row(rows[0]) if rows else None


# --- the phone's side ---------------------------------------------------------------------------------------------------------------------
async def submit(text: str, conn: Any = None) -> dict[str, Any]:
    """Leaves a sentence for the Mac. An earlier one still waiting is marked replaced (only the newest counts)."""
    text = (text or "").strip()
    if not text:
        raise ValueError("Type what you want, for example: Rabit Haus recap of the JD shoot, 35 seconds.")
    if len(text) > MAX_TEXT:
        raise ValueError(f"Keep it under {MAX_TEXT} characters.")
    await ensure_tables(conn)
    now = now_iso()
    await _run(conn, f"UPDATE {_table(conn, 'requests')} SET status = 'replaced', updated_at = ? WHERE status IN ('new', 'understood')", (now,))
    rows = await _run(conn, f"INSERT INTO {_table(conn, 'requests')} (text, status, created_at, updated_at) VALUES (?, 'new', ?, ?) RETURNING id", (text, now, now))
    return await _get(conn, int(rows[0][0]))


async def latest(conn: Any = None) -> dict[str, Any]:
    """The newest request (or None) and whether the Mac is online."""
    if not await tables_exist(conn):
        return {"request": None, "mac_online": False, "mac_seen_at": None}
    rows = await _run(conn, f"SELECT {', '.join(_COLUMNS)} FROM {_table(conn, 'requests')} ORDER BY id DESC LIMIT 1")
    beat = await _run(conn, f"SELECT seen_at FROM {_table(conn, 'worker')} WHERE id = 1")
    seen = beat[0][0] if beat else None
    return {"request": _row(rows[0]) if rows else None, "mac_online": bool(seen and seen >= _ago(MAC_ONLINE_SECONDS / 60)), "mac_seen_at": seen}


async def press_go(request_id: int, conn: Any = None) -> dict[str, Any]:
    req = await _get(conn, request_id)
    if req is None:
        raise LookupError("That request isn't there any more. Describe the edit again.")
    if req["status"] != "understood" or not (req["card"] or {}).get("ready"):
        raise ValueError("This card can't run as it stands." if req["status"] == "understood" else f"This request is {req['status']}, so it can't start.")
    if req["updated_at"] < _ago(CARD_EXPIRES_MINUTES):
        raise ValueError("That card is over half an hour old. Describe the edit again so the costs are current.")
    await _run(conn, f"UPDATE {_table(conn, 'requests')} SET status = 'go', updated_at = ? WHERE id = ? AND status = 'understood'", (now_iso(), request_id))
    return await _get(conn, request_id)


async def cancel(request_id: int, conn: Any = None) -> dict[str, Any]:
    req = await _get(conn, request_id)
    if req is None:
        raise LookupError("That request isn't there any more.")
    if req["status"] not in ("new", "understood", "go"):
        raise ValueError(f"This request is {req['status']}: " + ("it's already running on the Mac." if req["status"] in ("starting", "running") else "nothing to cancel."))
    await _run(conn, f"UPDATE {_table(conn, 'requests')} SET status = 'cancelled', updated_at = ? WHERE id = ?", (now_iso(), request_id))
    return await _get(conn, request_id)


# --- the Mac's side -----------------------------------------------------------------------------------------------------------------------
async def heartbeat(conn: Any = None) -> None:
    await _run(conn, f"""INSERT INTO {_table(conn, 'worker')} (id, seen_at) VALUES (1, ?) ON CONFLICT (id) DO UPDATE SET seen_at = excluded.seen_at""", (now_iso(),))


async def expire_stale(conn: Any = None) -> None:
    await _run(conn, f"UPDATE {_table(conn, 'requests')} SET status = 'expired', message = ?, updated_at = ? WHERE status = 'new' AND created_at < ?",
               ("The Mac didn't pick this up in time (was it off?). Send it again.", now_iso(), _ago(NEW_EXPIRES_MINUTES)))


async def claim(from_status: str, to_status: str, conn: Any = None) -> dict[str, Any] | None:
    """Takes the oldest request in `from_status` and moves it to `to_status` (one Mac does this, so no two runs take the same one)."""
    rows = await _run(conn, f"""UPDATE {_table(conn, 'requests')} SET status = ?, updated_at = ?
        WHERE id = (SELECT id FROM {_table(conn, 'requests')} WHERE status = ? ORDER BY id LIMIT 1) RETURNING id""", (to_status, now_iso(), from_status))
    return await _get(conn, int(rows[0][0])) if rows else None


async def update(request_id: int, conn: Any = None, *, status: str | None = None, card: dict | None = None, run: dict | None = None, message: str | None = None) -> None:
    sets, params = ["updated_at = ?"], [now_iso()]
    if status is not None:
        sets.append("status = ?"); params.append(status)
    if card is not None:
        sets.append("card_json = ?"); params.append(json.dumps(card, default=str))
    if run is not None:
        sets.append("run_json = ?"); params.append(json.dumps(run, default=str))
    if message is not None:
        sets.append("message = ?"); params.append(message[:500])
    await _run(conn, f"UPDATE {_table(conn, 'requests')} SET {', '.join(sets)} WHERE id = ?", (*params, request_id))
